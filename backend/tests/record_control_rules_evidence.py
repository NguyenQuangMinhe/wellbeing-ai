"""
Produces the multi-turn transcripts required by task 1002b's checklist item: "Multi-turn transcripts evidencing decline, topic change and clean close."

Non-interactive, i.e., scripted turns instead of input(), run against the same live backend, written to a Markdown
transcript for attaching as evidence.

Requires backend running (uvicorn app.main:app) and Ollama running
"""

import uuid
from pathlib import Path

import httpx

BASE_URL = "http://localhost:8000"
TIMEOUT = 120

OUTPUT_PATH = Path(__file__).parent / "evidence" / "1002b_conversational_control_transcripts.md"


def send(session_id: str, message: str) -> dict:
    response = httpx.post(
        f"{BASE_URL}/api/message",
        json={"session_id": session_id, "message": message},
        timeout=TIMEOUT,
    )
    response.raise_for_status()
    return response.json()


SCENARIOS = [
    {
        "name": "Decline (AC 9.1) - stage must not advance or reset",
        "turns": [
            "My presentation is on Friday, and the audience questions worry me.",
            "I don't want to answer that, I'd rather not talk about specifics.",
            "Actually, I think I'll go blank and feel nervous.",
        ],
        "expected_stages": ["Explore", "Explore", "Reflect"],
    },
    {
        "name": "Topic change (AC 9.2) - resets to Start, follows the new topic",
        "turns": [
            "My presentation is on Friday, and the audience questions worry me.",
            "Actually, I'd rather talk about my friend cancelling our dinner plans.",
            "I feel disappointed because I miss spending time with her.",
        ],
        "expected_stages": ["Explore", "Start", "Explore"],
    },
    {
        "name": "Clean close (AC 9.3) - closes without another question, stage held",
        "turns": [
            "My presentation is on Friday, and the audience questions worry me.",
            "I think I'll go blank and feel nervous about it.",
            "Let's stop here, that's enough for today.",
        ],
        "expected_stages": ["Explore", "Reflect", "Reflect"],
    },
]


def run_scenario(scenario: dict) -> list[str]:
    session_id = f"1002b-evidence-{uuid.uuid4()}"
    lines = [f"## {scenario['name']}", "", f"Session: `{session_id}`", ""]

    all_match = True
    for turn_number, (message, expected_stage) in enumerate(
        zip(scenario["turns"], scenario["expected_stages"]), start=1
    ):
        data = send(session_id, message)
        actual_stage = data["stage"]
        match = actual_stage == expected_stage
        all_match = all_match and match
        verdict = "PASS" if match else "FAIL"

        print(f"  turn {turn_number}: stage={actual_stage} (expected {expected_stage}) - {verdict}")

        lines.append(f"**Turn {turn_number} - User:** {message}")
        lines.append("")
        lines.append(f"**Assistant:** {data['message']}")
        lines.append("")
        lines.append(
            f"`stage={actual_stage}` (expected `{expected_stage}`) - **{verdict}** | "
            f"type={data['type']} risk_level={data['risk_level']} end_session={data['end_session']}"
        )
        lines.append("")

    lines.append(f"**Scenario result: {'PASS' if all_match else 'FAIL'}**")
    lines.append("")
    lines.append("---")
    lines.append("")
    return lines


def main():
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    all_lines = [
        "# 1002b conversational-control evidence",
        "",
        "Live transcripts generated by `record_control_rules_evidence.py` against the running backend.",
        "",
    ]

    for scenario in SCENARIOS:
        print(f"\n=== {scenario['name']} ===")
        all_lines.extend(run_scenario(scenario))

    OUTPUT_PATH.write_text("\n".join(all_lines), encoding="utf-8")
    print(f"\nTranscript written to {OUTPUT_PATH}")


if __name__ == "__main__":
    main()